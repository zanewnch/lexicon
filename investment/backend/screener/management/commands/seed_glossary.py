class Command(BaseCommand):
    help = '將術語資料 seed 進 SQLite GlossaryTerm 表'

    def handle(self, *args, **options):
        created = updated = 0
        for entry in GLOSSARY:
            key, term, category, description = entry[:4]
            example = entry[4] if len(entry) > 4 else ''
            _, is_new = GlossaryTerm.objects.update_or_create(
                key=key,
                defaults={'term': term, 'category': category, 'description': description, 'example': example},
            )
            if is_new:
                created += 1
            else:
                updated += 1
        self.stdout.write(self.style.SUCCESS(
            f'完成：新增 {created} 筆，更新 {updated} 筆'
        ))
