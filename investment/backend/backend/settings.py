# FinMind API token — 自動偵測 token 更換並回寫 SAVED_AT
FINMIND_TOKEN = os.environ.get('FINMIND_TOKEN', '')

if FINMIND_TOKEN and _env_path.exists():
    import hashlib
    from datetime import datetime

    _raw = _env_path.read_text(encoding='utf-8')
    _token_hash = hashlib.sha256(FINMIND_TOKEN.encode()).hexdigest()[:16]
    _old_hash = os.environ.get('FINMIND_TOKEN_HASH', '')

    if _token_hash != _old_hash:
        # Token 變了（或首次啟動），自動更新 SAVED_AT 和 HASH
        _now = datetime.now().strftime('%Y-%m-%dT%H:%M:%S')
        _updates = {
            'FINMIND_TOKEN_SAVED_AT': _now,
            'FINMIND_TOKEN_HASH': _token_hash,
        }
        _lines = _raw.splitlines()
        _existing_keys = set()
        _new_lines = []
        for _l in _lines:
            _stripped = _l.strip()
            if _stripped and not _stripped.startswith('#') and '=' in _stripped:
                _k = _stripped.partition('=')[0].strip()
                if _k in _updates:
                    _new_lines.append(f'{_k}={_updates[_k]}')
                    _existing_keys.add(_k)
                    continue
            _new_lines.append(_l)
        for _k, _v in _updates.items():
            if _k not in _existing_keys:
                _new_lines.append(f'{_k}={_v}')
        _env_path.write_text('\n'.join(_new_lines) + '\n', encoding='utf-8')
        os.environ['FINMIND_TOKEN_SAVED_AT'] = _now
        os.environ['FINMIND_TOKEN_HASH'] = _token_hash


