import logging
import copy


class ColoredFormatter(logging.Formatter):
    """根據 log level 與 module 名稱上色。"""

    LEVEL_COLORS = {
        'DEBUG':    '\033[36m',     # cyan
        'INFO':     '\033[32m',     # green
        'WARNING':  '\033[33m',     # yellow
        'ERROR':    '\033[31m',     # red
        'CRITICAL': '\033[1;31m',   # bold red
    }
    MODULE_COLORS = {
        'core.shioaji':     '\033[35m',   # magenta
        'account.service':  '\033[34m',   # blue
        'market.quote':     '\033[36m',   # cyan
        'market.twse':      '\033[33m',   # yellow
        'news.service':     '\033[32m',   # green
        'market.views':     '\033[95m',   # light magenta
        'screener.service': '\033[96m',   # light cyan
        'strategy.service': '\033[94m',   # light blue
    }
    RESET = '\033[0m'

    def format(self, record):
        record = copy.copy(record)
        level_color = self.LEVEL_COLORS.get(record.levelname, '')
        module_color = self.MODULE_COLORS.get(record.name, '\033[37m')  # default white
        record.levelname = f"{level_color}{record.levelname:<8}{self.RESET}"
        record.name = f"{module_color}{record.name}{self.RESET}"
        return super().format(record)


